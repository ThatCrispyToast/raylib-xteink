#ifndef XTEINK_DEVICE_H
#define XTEINK_DEVICE_H

#define XTEINK_X4 1
#define XTEINK_X3 2
#define XTEINK_X4_CLASSIC 3
#define XTEINK_X4_PRO 4
#ifndef XTEINK_DEVICE
#define XTEINK_DEVICE XTEINK_X4
#endif

#if XTEINK_DEVICE == XTEINK_X3
#define XTEINK_DEVICE_ID "x3"
#define XTEINK_DEVICE_NAME "Xteink X3"
#define XTEINK_WIDTH 528
#define XTEINK_HEIGHT 792
#define XTEINK_PHYSICAL_WIDTH_MM 52
#define XTEINK_PHYSICAL_HEIGHT_MM 78
#elif XTEINK_DEVICE == XTEINK_X4 || XTEINK_DEVICE == XTEINK_X4_CLASSIC || XTEINK_DEVICE == XTEINK_X4_PRO
#define XTEINK_WIDTH 480
#define XTEINK_HEIGHT 800
#define XTEINK_PHYSICAL_WIDTH_MM 56
#define XTEINK_PHYSICAL_HEIGHT_MM 93
#if XTEINK_DEVICE == XTEINK_X4
#define XTEINK_DEVICE_ID "x4"
#define XTEINK_DEVICE_NAME "Xteink X4"
#elif XTEINK_DEVICE == XTEINK_X4_CLASSIC
#define XTEINK_DEVICE_ID "x4-classic"
#define XTEINK_DEVICE_NAME "Xteink X4 Classic"
#else
#define XTEINK_DEVICE_ID "x4-pro"
#define XTEINK_DEVICE_NAME "Xteink X4 Pro"
#endif
#else
#error "Unknown XTEINK_DEVICE"
#endif

#define XTEINK_HAS_TOUCH (XTEINK_DEVICE == XTEINK_X4_PRO)
#define XTEINK_HAS_FRONTLIGHT (XTEINK_DEVICE == XTEINK_X4_PRO)
#define XTEINK_PANEL_WIDTH XTEINK_HEIGHT
#define XTEINK_PANEL_HEIGHT XTEINK_WIDTH
#define XTEINK_FRAME_BYTES (XTEINK_WIDTH*XTEINK_HEIGHT/8)
#define XTEINK_GRAY_BYTES (XTEINK_WIDTH*XTEINK_HEIGHT/4)

// Only the original X4 has a verified emulator crop.
#if XTEINK_DEVICE == XTEINK_X4
#define XTEINK_VISIBLE_TOP 10
#define XTEINK_VISIBLE_HEIGHT 786
#else
#define XTEINK_VISIBLE_TOP 0
#define XTEINK_VISIBLE_HEIGHT XTEINK_HEIGHT
#endif

#endif
