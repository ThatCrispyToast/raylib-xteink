#!/usr/bin/env python3
"""Expand raylib's built-in font into immutable flash data for the SRAM-limited X4."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = (root/'vendor/raylib/src/rtext.c').read_text()
def numbers(name):
    data = re.search(r'\b'+name+r'\[\d+\]\s*=\s*\{([^}]+)\}',source).group(1)
    return [int(n,0) for n in re.findall(r'0x[0-9a-f]+|\d+',data)]
bits, widths = numbers('defaultFontData'), numbers('charsWidth')
assert len(bits)==512 and len(widths)==224
atlas = bytes(v for i in range(16384) for v in (255,255 if bits[i//32] & (1 << (i%32)) else 0))
rects, glyphs, offsets = [], bytearray(), []
line, x = 0,1
for width in widths:
    nx=x+width+1
    if nx>=128:
        line+=1
        x=1
        nx=2+width
    y=1+line*11
    rects.append((x,y,width,10))
    offsets.append(len(glyphs))
    for row in range(y,y+10): glyphs.extend(atlas[(row*128+x)*2:(row*128+x+width)*2])
    x=nx

def array(name,data):
    lines=['static const unsigned char '+name+'[] =']
    for i in range(0,len(data),32): lines.append('    "'+''.join(f'\\x{v:02x}' for v in data[i:i+32])+'"')
    return '\n'.join(lines)+';\n'
text='// Generated by scripts/generate-font.py from raylib rtext.c; upstream zlib license applies.\n'
text+=array('x4_font_atlas',atlas)+array('x4_font_glyph_pixels',glyphs)
text+='static const unsigned short x4_font_rects[224][5] = {\n'
text+=''.join('    {'+','.join(map(str,(*rect,offset)))+'},\n' for rect,offset in zip(rects,offsets))+'};\n'
(root/'src/x4_font_data.h').write_text(text)
print(f'Generated {len(atlas)+len(glyphs)} bytes of immutable font pixels')
