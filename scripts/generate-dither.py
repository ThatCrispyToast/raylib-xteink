#!/usr/bin/env python3
"""Regenerate the packed four-pixel Bayer lookup used by the X4 converter."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
masks = ((14,12,14,12),(8,14,8,12),(14,8,14,12),(8,12,8,12))
lines = ["// Generated by scripts/generate-dither.py: four gray pixels -> byte-spaced bits.",
         "static const uint32_t dither_lut[4][256] = {"]
for row in masks:
    values = [sum(((row[x] >> ((byte >> (6-2*x)) & 3)) & 1) << (8*x)
                  for x in range(4)) for byte in range(256)]
    lines.append("    {")
    for start in range(0,256,8):
        lines.append("        " + ",".join(f"0x{v:08x}" for v in values[start:start+8]) + ",")
    lines.append("    },")
lines.append("};")
(root / "src/x4_dither_lut.h").write_text("\n".join(lines) + "\n")
